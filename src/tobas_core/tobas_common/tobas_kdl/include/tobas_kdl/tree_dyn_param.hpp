#pragma once

#include "./tree_id_solver.hpp"

namespace tobas::kdl
{
/** Tree version of `kdl::ChainDynParam`. */
class TreeDynParam : public TreeSolverI
{
  using super = TreeSolverI;

public:
  explicit TreeDynParam(const Tree& _tree, const Vector& _grav = Vector(0.0, 0.0, -st::kGravity));

  void updateInternalDataStructures() override;

  /**
   * Compute the torque generated by Coriolis force.
   *
   * @param _q Joint angles.
   * @param _qd Joint angular velocities.
   */
  const JntArray& jntToCoriolis(const JntArray& _q, const JntArray& _qd);

  /**
   * Compute the torque generated by gravity.
   *
   * @param _q Joint angles.
   */
  const JntArray& jntToGravity(const JntArray& _q);

private:
  TreeIdSolver rne_coriolis_;
  TreeIdSolver rne_gravity_;

  JntArray q_zero_;

  void resize();
};
}  // namespace tobas::kdl
